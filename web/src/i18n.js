const patternCache = new Map()

function matchPattern(dict, zh) {
  for (const key of Object.keys(dict)) {
    if (!key.includes('{')) continue
    let p = patternCache.get(key)
    if (!p) {
      const names = []
      const src = key
        .replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
        .replace(/\\\{([^{}]+)\\\}/g, (_, n) => {
          names.push(n)
          return '(.+?)'
        })
      p = { re: new RegExp('^' + src + '$'), names }
      patternCache.set(key, p)
    }
    const m = p.re.exec(zh)
    if (m) {
      let out = dict[key]
      p.names.forEach((n, i) => {
        out = out.replaceAll('{' + n + '}', m[i + 1])
      })
      return out
    }
  }
  return null
}

export function t(zh, params) {
  let s = zh
  if (lang.value === 'en') {
    s = en[zh] ?? matchPattern(en, zh) ?? zh
  } else if (lang.value === 'zh-Hant') {
    s = zhHant[zh] ?? matchPattern(zhHant, zh) ?? zh
  }
  if (params) {
    for (const k of Object.keys(params)) {
      s = s.replaceAll('{' + k + '}', String(params[k]))
    }
  }
  return s
}
