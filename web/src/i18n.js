import { ref } from 'vue'

function initialLang() {
  const stored = localStorage.getItem('namakani_lang')
  if (stored === 'zh-Hans' || stored === 'zh-Hant' || stored === 'en') return stored
  if (stored === 'zh') {
    localStorage.setItem('namakani_lang', 'zh-Hans')
    return 'zh-Hans'
  }
  const nav = (navigator.language || 'en').toLowerCase()
  if (nav.startsWith('zh')) {
    return nav.includes('hant') || nav.startsWith('zh-tw') || nav.startsWith('zh-hk') || nav.startsWith('zh-mo')
      ? 'zh-Hant'
      : 'zh-Hans'
  }
  return 'en'
}
export const lang = ref(initialLang())

export function setLang(v) {
  lang.value = v
  localStorage.setItem('namakani_lang', v)
  document.documentElement.lang = v
}
document.documentElement.lang = lang.value

export function intlLocale() {
  return lang.value === 'zh-Hans' ? 'zh-CN' : lang.value === 'zh-Hant' ? 'zh-TW' : 'en-US'
}

