// Generates src/language-names.js from src/languages.js.
// Data: Unicode CLDR 49 release files (npm cldr-localenames-full@49.0.0); CLDR_DIR points at its main/ dir.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const dir = dirname(fileURLToPath(import.meta.url))
const cldr = process.env.CLDR_DIR
if (!cldr) {
  console.error('set CLDR_DIR to the main/ dir of cldr-localenames-full@49.0.0')
  process.exit(1)
}
const codes = [...readFileSync(join(dir, 'src/languages.js'), 'utf8').matchAll(/"([^"]+)"/g)].map((m) => m[1])

function langMap(loc) {
  try {
    return JSON.parse(readFileSync(join(cldr, loc, 'languages.json'), 'utf8')).main[loc].localeDisplayNames.languages
  } catch {
    return null
  }
}
const zh = langMap('zh')
const en = langMap('en')

const table = {}
let zhHit = 0
let enHit = 0
let autoHit = 0
const resZh = []
const resEn = []
for (const code of codes) {
  const own = langMap(code)
  const row = [zh?.[code] ?? null, en?.[code] ?? null, own?.[code] ?? null]
  table[code] = row
  if (row[0]) zhHit++
  if (row[1]) enHit++
  if (row[2]) autoHit++
  if (!row[0] && !row[2]) resZh.push(code)
  if (!row[1] && !row[2]) resEn.push(code)
}

const lines = codes.map((c) => `  ${JSON.stringify(c)}: ${JSON.stringify(table[c])},`)
const out = `// Generated by gen-language-names.mjs. Do not edit.\n// Source: Unicode CLDR 49 (cldr-localenames-full). Each row: [zh name, en name, autonym]; null where CLDR has no name.\nexport const LANGUAGE_NAMES = {\n${lines.join('\n')}\n}\n`
writeFileSync(join(dir, 'src/language-names.js'), out)
console.log(`rows ${codes.length}, zh ${zhHit}, en ${enHit}, autonym ${autoHit}`)
console.log(`unresolvable in zh UI (${resZh.length}): ${resZh.join(' ')}`)
console.log(`unresolvable in en UI (${resEn.length}): ${resEn.join(' ')}`)
